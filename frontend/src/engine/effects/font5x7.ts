export const FONT_COLS = 5;
export const FONT_ROWS = 7;

/** 有点阵的字符（大写形式） */
export function hasGlyph(ch: string): boolean {
  return ch.toUpperCase() in GLYPHS;
}

/**
 * 取一个字符的点阵：7 行 × 5 列的布尔表，行优先；没有这个字的返回 null。
 * 小写按大写画，空格不画。
 */
export function glyphOf(ch: string): boolean[][] | null {
  const rows = GLYPHS[ch.toUpperCase()];
  if (!rows) return null;
  return rows.map((row) => Array.from({ length: FONT_COLS }, (_, i) => row[i] === '#'));
}

/** 字符串里能画出来的字：去掉空白与没有点阵的字符，按顺序留下来 */
export function drawableChars(text: string): string[] {
  const out: string[] = [];
  for (const ch of text) if (ch.trim() && hasGlyph(ch)) out.push(ch.toUpperCase());
  return out;
}
